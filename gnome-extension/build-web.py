#!/usr/bin/env python3
"""Bundle the panel pets' drawing code for the website (site/pets.js).
  gnome-extension/build-web.py            write site/pets.js
  gnome-extension/build-web.py --check    exit 1 if site/pets.js is out of date (used by the tests)
The pets in glob@living-sky/pets/ are written for GNOME's gjs (`imports.cairo`, `var def`); on the page they
run on site/cairo-shim.js (window.LivingSkyCairo, a cairo-like API over Canvas 2D). The bundle exposes
window.LivingSkyPets = {newAnim, tick, drawPet, PETS}. Re-run after changing any pet.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'glob@living-sky', 'pets')
OUT = os.path.join(HERE, '..', 'site', 'pets.js')
ORDER = ['mimi', 'pip', 'bun', 'nyx', 'cubo', 'ember']      # the order the site shows them


def build():
    core = open(os.path.join(SRC, 'core.js')).read()
    core = core.replace("const Cairo = imports.cairo;", "const Cairo = window.LivingSkyCairo;")
    core = re.sub(r"^'use strict';\n", '', core, flags=re.M)
    if re.search(r'^[^/\n]*\bimports\.', core, re.M):
        sys.exit('build-web: core.js still uses imports.*')
    pets = sorted(n[:-3] for n in os.listdir(SRC) if n.endswith('.js') and n != 'core.js')
    missing = set(pets) ^ set(ORDER)
    if missing:
        sys.exit('build-web: pets and ORDER differ: %s' % ', '.join(sorted(missing)))
    out = ['// GENERATED by gnome-extension/build-web.py from gnome-extension/glob@living-sky/pets/*.js:',
           '// do not edit; change the pets there and re-run the script.',
           '(function () {', "'use strict';", core.rstrip(), '', 'const PETS = {};']
    for pid in ORDER:
        s = open(os.path.join(SRC, pid + '.js')).read()
        if re.search(r'^[^/\n]*\bimports\.', s, re.M):
            sys.exit('build-web: %s.js uses imports.*' % pid)
        s = re.sub(r"^'use strict';\n", '', s, flags=re.M).rstrip()
        out += ['PETS.%s = (function () {' % pid, s, 'return def;', '})();']
    out += ['window.LivingSkyPets = {newAnim, tick, drawPet, PETS, ORDER: %r};' % ORDER, '})();', '']
    return '\n'.join(out)


if __name__ == '__main__':
    text = build()
    if '--check' in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        sys.exit(0 if old == text else 'site/pets.js is out of date: run gnome-extension/build-web.py')
    open(OUT, 'w').write(text)
    print(os.path.normpath(OUT))
